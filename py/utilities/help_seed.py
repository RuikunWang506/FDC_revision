from __future__ import annotations


def _has_cjk(text: str) -> bool:
    return any('\u4e00' <= ch <= '\u9fff' for ch in (text or ''))


def _split_title(title: str) -> tuple[str, str]:
    t = title or ''
    if ' / ' not in t:
        return t, t
    left, right = t.rsplit(' / ', 1)
    if _has_cjk(right):
        return left.strip(), right.strip()
    en, zh = t.split(' / ', 1)
    return en.strip(), zh.strip()


def _html(lead: str, heading_how: str, heading_tips: str, steps, tips, idx: int) -> str:
    parts = [f'<p>{lead}</p>']
    if steps:
        parts.append(f'<h3>{heading_how}</h3><ol>')
        for pair in steps:
            parts.append(f'<li>{pair[idx]}</li>')
        parts.append('</ol>')
    if tips:
        parts.append(f'<h3>{heading_tips}</h3><ul>')
        for pair in tips:
            parts.append(f'<li>{pair[idx]}</li>')
        parts.append('</ul>')
    return ''.join(parts)


def _art(slug, title, category, sort_order, en, zh, steps=None, tips=None):
    title_en, title_zh = _split_title(title)
    return {
        'slug': slug,
        'title': title_en,
        'title_zh': title_zh,
        'category': category,
        'sort_order': sort_order,
        'body_html': _html(en, 'How to use', 'Tips', steps, tips, 0),
        'body_html_zh': _html(zh, '怎么用', '提示', steps, tips, 1),
    }


